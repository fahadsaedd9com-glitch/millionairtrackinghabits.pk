// Writes public/config.js from the API_URL environment variable (used when the frontend is hosted
// separately from the backend, e.g. Netlify). Example: API_URL=https://habits-api.onrender.com
const fs = require('fs'), path = require('path');
const url = String(process.env.API_URL || '').trim().replace(/\/+$/, '');
if (url && !/^https?:\/\/[^\s]+$/.test(url)) { console.error('API_URL must start with http:// or https://'); process.exit(1); }
if (!url) console.warn('[write-config] API_URL is empty: the frontend will call /api on its own domain.');
const body = '// generated by scripts/write-config.js\nwindow.APP_CONFIG = ' + JSON.stringify({ API_URL: url }) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'public', 'config.js'), body);
console.log('Wrote public/config.js ->', url || '(same-origin)');
